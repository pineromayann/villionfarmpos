/**
 * Replay a gzipped dump into a brand new SQLite database and return the handle.
 *
 * This is the closest a test can get to a real restore: an empty database is
 * rebuilt purely from the backup artifact.
 *
 * @return array{0: PDO, 1: string}
 */
function replayDumpIntoFreshDatabase(Backup $backup): array
{
    $sql = (string) gzdecode((string) Storage::disk($backup->disk)->get($backup->path));
    $path = tempnam(sys_get_temp_dir(), 'vfprestore-').'.sqlite';

    $pdo = new PDO('sqlite:'.$path);
    $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
    $pdo->exec($sql);

    return [$pdo, $path];
}

/**
 * Read a whole table out of the replayed database.
 *
 * @return array<int, array<string, mixed>>
 */
function rowsFrom(PDO $pdo, string $table): array
{
    return $pdo->query('SELECT * FROM "'.$table.'" ORDER BY id')->fetchAll(PDO::FETCH_ASSOC);
}

